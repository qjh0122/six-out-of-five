/**
 * 成就页渲染（node pwa/test/achievements-view.test.js）
 *
 * 渲染层不产生数字（数字由 achievements.js 判定），所以这里只锁「看得见的东西」：
 *
 *   1. **未解锁的成就也显示名字与描述**（用户裁定：不做 ??? 猜谜）；
 *   2. 已解锁 / 未解锁的卡片在标记上必须能区分（is-ok），否则玩家分不出拿到了没有；
 *   3. 概率为 null 时显示「—」，**不能显示 0%** ——
 *      「还没打过」和「打过一次没拿到」是两件不同的事，混成 0% 会误导；
 *   4. 信息档入口带 data-ach-open（点击委托靠这个属性找目标）。
 *
 * 反例检查：拿一份**完全空**的档案跑一遍，页面必须能正常输出（不能抛、不能空字符串）。
 * 新用户第一次点进来就是这个状态 —— 这是最常被忽略的那条路径。
 */
'use strict';

var AV = require('../js/achievementsView.js');
var Ach = require('../js/achievements.js');

var pass = 0, fail = 0;
function ok(cond, name, extra) {
  if (cond) pass += 1;
  else { fail += 1; console.error('✗ ' + name + (extra ? ' — ' + extra : '')); }
}
function eq(a, b, name) {
  ok(a === b, name, 'got ' + JSON.stringify(a) + ' want ' + JSON.stringify(b));
}

/* ================================================================
 * 一、空档案（新用户第一次进来）
 * ================================================================ */
var empty = {
  playerId: 'p0', nickname: '新人', games: 0,
  ach: Ach.blank()
};
var h0 = AV.pageHtml(empty, Ach, { isMe: true });
ok(typeof h0 === 'string' && h0.length > 500, '空档案也能渲染出整页（不抛、不空串）');
ok(h0.indexOf('0') >= 0, '顶部显示 0 个已解锁');
ok(h0.indexOf('十点半成瘾') >= 0, '★ 一条都没解锁时，成就名字照样显示');
ok(h0.indexOf('还没打过带牌型的局') >= 0, '空态给出解释（而不是一片空网格）');
eq(h0.indexOf('is-ok'), -1, '空档案没有任何卡片带 is-ok');

/* ================================================================
 * 二、有数据的档案
 * ================================================================ */
var prof = {
  playerId: 'p1', nickname: '玩家A', games: 20, longestStreak: 6, bestNet: 16,
  ach: {
    /* 十点半 3 次 / 参与 6 次 = 50%，豹子 0 次 / 参与 6 次 = 0% */
    t: { th: 3, lp: 0, nn: 12 },
    n: { tenhalf: 6, piaosanye: 6, douniu: 20 },
    vs: 4, vsl: 2, vsn: 6,
    s1: 1, s2: 0, sa: 0, sw: 1,
    r7: 0, r8: 0,
    since: 1700000000000
  }
};
var h = AV.pageHtml(prof, Ach, { isMe: true });

ok(h.indexOf('十点半成瘾') >= 0, '名字在');
ok(h.indexOf('不多不少正好 10.5') >= 0, '描述在（v114：描述不再写「十次」这类门槛）');
ok(h.indexOf('is-ok') >= 0, '有解锁的卡片');
/* v112：牌型成就展示的是**次数**（+ 出现率），不再画 3/10 的进度条 ——
 * 玩得久的人早就顶满了，停在 20/20 会让人以为系统不记了。
 * 2026-11-11 第 3 批：百分比前面补上「出现率」，否则和「胜率」长得一模一样
 * （都是裸百分比，玩家分不清「我拿到过」和「我赢了」）。 */
ok(h.indexOf('3 次 · 出现率 50.0%') >= 0, '★ 牌型卡展示次数与出现率（3 次 · 出现率 50.0%）');
ok(h.indexOf('3 / 10') < 0, '不再出现 3 / 10 这种进度写法');

/* 概率：十点半 3 次 / 6 次参与 = 50.0% */
ok(h.indexOf('50.0%') >= 0, '★ 概率按「命中 / 参与该组次数」算（3/6 = 50.0%）');
/* 豹子 0 次 / 6 次参与 = 0.0%（打过但没拿到，是 0 不是 —） */
ok(h.indexOf('0.0%') >= 0, '★ 打过但没拿到 → 0.0%（不是 —）');
/* 五花牛：斗牛组参与 20 次、五花牛 0 次 → 0.0%；而「—」留给真的没分母的项 */
ok(h.indexOf('—') >= 0, '分母为 0 的牌型显示「—」而不是 0%');

ok(h.indexOf('大牌对撞') >= 0, '对撞汇总行在');
ok(h.indexOf('66.7%') >= 0, '★ 对撞胜率 4 / 6 = 66.7%');

/* 四个系列标题都在 */
['牌型', '对撞', '通吃', '战绩'].forEach(function (t) {
  ok(h.indexOf('>' + t) >= 0 || h.indexOf(t + ' <') >= 0 || h.indexOf(t) >= 0,
    '系列标题出现：' + t);
});

/* 战绩系列靠档案字段：games=20 → 常客解锁、老油条没解锁 */
ok(h.indexOf('常客') >= 0, '战绩系列按 games 判定（常客出现）');
ok(h.indexOf('100') >= 0, '老油条的目标值 100 出现在进度里');

/* 别人看：标题文案不同 */
var hAnon = AV.pageHtml(prof, Ach, { isMe: false });
ok(hAnon.indexOf('玩家A 已解锁') >= 0, '看别人时标题写对方名字');
ok(h0.indexOf('你已解锁') >= 0, '看自己时写「你已解锁」');

/* ================================================================
 * 二·补、三类数字口径（2026-11-11 第 3 批）
 *
 * 背景：以前「已经达成的次数型成就」只写「277 次」，玩家把它读成进度，
 * 于是问「我打了两百多场，这个成就怎么是 277」。次数没错，错在它像进度条上的数字。
 * 现在四类各写各的：
 *   · 进度条   → 「7 / 10」（只有六条）
 *   · 牌型     → 「3 次 · 出现率 50.0%」
 *   · 对撞胜率 → 「胜率 46.0% · 对撞 100 次」/ 样本不够时「对撞 37 / 100 次 · 胜率 70.3%」
 *   · 次数型   → 「已达成 · 累计 N 次」/「还差 N 次」/「未达成」
 * ================================================================ */
function pageWithAch(patch) {
  var a = Ach.blank();
  Object.keys(patch).forEach(function (k) { a[k] = patch[k]; });
  return AV.pageHtml({ playerId: 'pz', nickname: 'Z', games: 50, ach: a }, Ach, { isMe: true });
}

var pAch = pageWithAch({ s1: 3 });   // v116：一巡清场门槛 1→3
ok(pAch.indexOf('已达成 · 累计 3 次') >= 0,
  '★ 次数型已达成写「已达成 · 累计 N 次」——「已达成」必须在数字前面，否则那串数字会被读成进度');
ok(pAch.indexOf('还差 1 次') < 0, '刚好达标时不会同时写「还差」');

var pGap = pageWithAch({ sw: 4 });
ok(pGap.indexOf('还差 6 次') >= 0, '★ 次数型未达成写「还差 N 次」（常胜将军 4/10）');
ok(pGap.indexOf('已达成 · 累计 0 次') < 0, '没达成的不会写成已达成');

var pNever = pageWithAch({});
ok(pNever.indexOf('未达成') >= 0, '★ 一次都没有的写「未达成」，不是「还差 1 次」');

var pGated = pageWithAch({ vsn: 37, vs: 26 });
ok(pGated.indexOf('对撞 37 / 100 次 · 胜率 70.3%') >= 0,
  '★ 样本不够时先报样本进度，但胜率照样写出来（让人看见自己撞得准，只是还没撞够）');

var pMet = pageWithAch({ vsn: 100, vs: 46 });
ok(pMet.indexOf('胜率 46.0% · 对撞 100 次') >= 0,
  '★ 样本够了就写「胜率 x% · 对撞 N 次」，分母跟在后面（比率离开分母没有意义）');

var pFull = pageWithAch({ vsn: 100, vs: 100 });
ok(pFull.indexOf('胜率 100% · 对撞 100 次') >= 0, '100% 不写成 100.0%');

/* 对撞系列的阈值只在**系列提示**里写一次（卡片上不重复写 —— 次数型成就上
 * 「写门槛」已经被否过一次，会被读成上限）。但必须写清楚：
 * 46% 以上亮遇强则强、34% 以下亮外强中干、中间两条都不亮 ——
 * 不写的话，同一个人会看到两张卡显示同一个胜率、一明一暗，必然问「为什么不亮」。 */
ok(h.indexOf('46% 以上亮「遇强则强」') >= 0 && h.indexOf('34% 以下亮「外强中干」') >= 0,
  '★ 对撞系列提示里写清了 46% / 34% 两条阈值与真空区');
ok(h.indexOf('中间两条都不亮') >= 0, '★ 提示里说明了 34%~46% 是真空区（不是漏判）');
ok(h.indexOf('需≥46%') < 0 && h.indexOf('需≥34%') < 0,
  '卡片上不重复写阈值（八张卡各背一串数字没必要，规则看系列提示）');

/* ================================================================
 * 三、信息档入口行
 * ================================================================ */
var row = AV.entryRowHtml({ playerId: 'p9', achCount: 12, achTotal: 26 });
ok(row.indexOf('data-ach-open="p9"') >= 0, '★ 入口带 data-ach-open，点击委托靠它找人');
ok(row.indexOf('12 / 26') >= 0, '显示解锁数');
ok(row.indexOf('<button') === 0, '是一整条按钮（整卡唯一的可点区域）');

eq(AV.entryRowHtml(null), '', '没有档案时不渲染这一行（而不是渲染个空按钮）');
eq(AV.entryRowHtml({}), '', '缺 playerId 时也不渲染');
var noCount = AV.entryRowHtml({ playerId: 'px' });
ok(noCount.indexOf('0 / 0') >= 0, '缺计数时退化成 0 / 0，不出现 NaN 或 undefined');

/* ================================================================
 * 四、概率格式化
 * ================================================================ */
eq(AV.rateText(null), '—', 'null → 破折号');
eq(AV.rateText(0), '0.0%', '0 → 0.0%');
eq(AV.rateText(0.0005), '<0.1%', '极小概率不显示成 0.0%（那是「一次都没有」的意思）');
eq(AV.rateText(0.5), '50.0%', '0.5 → 50.0%');
eq(AV.rateText(0.125), '12.5%', '0.125 → 12.5%');

/* XSS：昵称与描述都进 HTML，必须转义 */
var evil = AV.pageHtml({ playerId: 'p', nickname: '<img onerror=1>', games: 0, ach: Ach.blank() }, Ach, { isMe: false });
eq(evil.indexOf('<img'), -1, '★ 昵称里的标签被转义（成就页会把昵称拼进标题）');

/* ================================================================
 * 七、点「成就」进整屏页时，浮层必须一起关掉（v119 修的那条报障）
 *
 * 这件事只有浏览器能证明（journey [9a] 就是干这个的），源码层再钉一道：
 * 那个点击委托里漏掉任何一个宿主，都会变成「成就页打开了、卡片还盖在上面」。
 * 被报过的版本正是漏了 profile-modal —— 只关了座位信息档（.ss-info）。
 * ================================================================ */
{
  var fs2 = require('fs'), path2 = require('path');
  var gameSrc = fs2.readFileSync(path2.join(__dirname, '..', 'js', 'game.js'), 'utf8');
  var at = gameSrc.indexOf("closest('[data-ach-open]')");
  ok(at > 0, '★ 有 data-ach-open 的点击委托（档案卡与座位档共用一条）');
  var seg = at > 0 ? gameSrc.slice(at, at + 1200) : '';
  ok(/closeSeatSheet\(\)/.test(seg), '★ 委托里关掉了座位信息档（.ss-info 宿主）');
  ok(/closeProfile\(\)/.test(seg),
    '★ 委托里也关掉了档案卡（.profile-box 宿主）—— 漏一个就是「成就页被一张卡挡住」');
  /* 顺序：先关浮层再切屏。反过来的话，关档案卡那一下的焦点归还会落到
   * 一个已经不可见的元素上，而且中间会闪出一帧「成就页 + 卡片」。 */
  var iClose = seg.indexOf('closeProfile()');
  var iOpen = seg.indexOf('openAchievements(pid');
  ok(iClose > 0 && iOpen > iClose, '关完浮层才打开成就页（顺序不能反）');
}

/* ================================================================
 * 汇总
 *
 * ★ 格式必须与其它测试一致（「通过 N 项，失败 M 项」）：scripts/run-tests.js
 * 用这条正则取数，取不到就退回数 PASS 行 —— 而这个文件的 ok() 不打 PASS 行，
 * 于是它长期在汇总里显示「0 项」，算总数时整个文件都被漏掉。
 * 数字小看不出来，但它意味着「131 文件 / N 断言」这句话里有一个文件的
 * 几十条断言从来没被数进去过。
 * ================================================================ */
console.log('\n' + (fail === 0 ? '全部通过' : '有失败'));
console.log('通过 ' + pass + ' 项，失败 ' + fail + ' 项');
if (fail) process.exit(1);
